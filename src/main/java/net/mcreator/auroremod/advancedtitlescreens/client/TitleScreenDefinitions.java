	public static final List<TitleScreenDef> ALL = new ArrayList<>();
	@Nullable
	private static TitleScreenDef active;
	private static boolean picked;
	static {
		build();
		TitleScreenApi.applySaved();
	}

	private static void build() {
		ALL.add(create_Homescreen());
	}

	/** Rebuilds every definition exactly as designed (keeps the same title screen picked), then re-applies the
	 *  procedure changes that are still kept. */
	static synchronized void reload() {
		String keep = active == null ? null : active.id;
		ALL.clear();
		build();
		active = null;
		for (TitleScreenDef def : ALL)
			if (def.id.equals(keep))
				active = def;
		picked = active != null;
		TitleScreenApi.reapply();
	}

	private TitleScreenDefinitions() {
	}

	/** The title screen used for this game session: a weighted random pick among enabled ones, made once. */
	@Nullable
	public static TitleScreenDef active() {
		if (!picked) {
			picked = true;
			int total = 0;
			for (TitleScreenDef def : ALL)
				if (def.enabled)
					total += Math.max(1, def.selectionWeight);
			if (total > 0) {
				int roll = RandomSource.create().nextInt(total);
				for (TitleScreenDef def : ALL) {
					if (!def.enabled)
						continue;
					roll -= Math.max(1, def.selectionWeight);
					if (roll < 0) {
						active = def;
						break;
					}
				}
			}
		}
		return active;
	}

